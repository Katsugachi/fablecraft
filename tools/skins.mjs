// Pack vanilla 1.21.5 entity skins (src-assets/vanilla) into the fablecraft
// sheet format ([w, h, ARGB palette, base64 indices]) -> src/skins_extra.js.
// Villager skins are composited: base villager skin + biome type overlay
// (robe colour) + profession overlay (chest symbol), matching how vanilla
// layers the 64x64 villager textures.
//   node tools/skins.mjs
import { PNG } from 'pngjs';
import fs from 'node:fs';
import path from 'node:path';

const ENT = '/home/user/src-assets/vanilla/assets/minecraft/textures/entity/';
const OUT = path.join(process.cwd(), 'src/skins_extra.js');

function read(f) {
  const p = PNG.sync.read(fs.readFileSync(path.join(ENT, f)));
  if (p.width !== 64 || (p.height !== 32 && p.height !== 64)) throw new Error('bad size ' + f);
  return { w: p.width, h: p.height, data: p.data };
}
// composite layers top-to-bottom (last non-transparent wins)
function compose(...pngs) {
  const [base] = pngs;
  const w = base.width, h = base.height;
  const out = new Uint8Array(w * h * 4);
  for (const p of [...pngs].reverse()) {
    for (let i = 0; i < w * h; i++) {
      const a = p.data[i * 4 + 3];
      if (a > 0) {
        out[i * 4] = p.data[i * 4];
        out[i * 4 + 1] = p.data[i * 4 + 1];
        out[i * 4 + 2] = p.data[i * 4 + 2];
        out[i * 4 + 3] = a;
      }
    }
  }
  return { w, h, data: out };
}
function toEntry(img) {
  const pal = new Map();
  const idx = [];
  for (let i = 0; i < img.w * img.h; i++) {
    const o = i * 4;
    const key = (img.data[o + 3] << 24) | (img.data[o] << 16) | (img.data[o + 1] << 8) | img.data[o + 2];
    let pi = pal.get(key);
    if (pi === undefined) { pi = pal.size; pal.set(key, pi); }
    idx.push(pi);
  }
  const palette = [...pal.entries()].map(([pi, argb]) => argb);
  // base64 of 1-byte indices
  let bin = '';
  for (const i of idx) bin += String.fromCharCode(i);
  return [img.w, img.h, palette, Buffer.from(bin, 'binary').toString('base64')];
}

const out = {};

// ---- villager (14 professions x 5 biome types) -------------------------------
const base = read('villager/villager.png');
const TYPES = { plains: 'villager/type/plains.png', desert: 'villager/type/desert.png', savanna: 'villager/type/savanna.png', snow: 'villager/type/snow.png', taiga: 'villager/type/taiga.png' };
const typePng = {};
for (const [t, f] of Object.entries(TYPES)) typePng[t] = read(f);
const PROFS = ['armorer', 'butcher', 'cartographer', 'cleric', 'farmer', 'fisherman', 'fletcher', 'leatherworker', 'librarian', 'mason', 'nitwit', 'shepherd', 'toolsmith', 'weaponsmith'];
const profPng = {};
for (const p of PROFS) profPng[p] = read('villager/profession/' + p + '.png');
out.villager_base = toEntry(base);
for (const t in typePng) out['villager_type_' + t] = toEntry(typePng[t]);
for (const p of PROFS) out['villager_prof_' + p] = toEntry(profPng[p]);

// ---- iron golem ----------------------------------------------------------------
// 1.21.5 retextured the golem onto a 128x128 non-standard UV sheet; fablecraft
// box models need the classic 64x32 cube layout, so we paint an iron sheet in
// vanilla's iron armour palette (mottled #808080-ish with darker specks).
{
  const w = 64, h = 32;
  const data = new Uint8Array(w * h * 4);
  let s = 123456789;
  const rnd = () => (s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const o = (y * w + x) * 4;
    let v = 128 + Math.floor(rnd() * 22 - 11);
    if (rnd() < 0.06) v -= 26;
    if (rnd() < 0.04) v += 18;
    data[o] = data[o + 1] = data[o + 2] = v;
    data[o + 3] = 255;
  }
  out.iron_golem = toEntry({ w, h, data });
}

// ---- cat (classic tabby, as in vanilla village cats) -----------------------------
out.cat = toEntry(read('cat/tabby.png'));

const js = `// GENERATED by tools/skins.mjs — do not edit.
// Vanilla 1.21.5 entity skins in fablecraft sheet format [w, h, palette, base64].
export const EXTRA_SHEETS = ${JSON.stringify(out)};
`;
fs.writeFileSync(OUT, js);
console.log('wrote', OUT, (js.length / 1024).toFixed(1), 'KB,', Object.keys(out).length, 'sheets');
