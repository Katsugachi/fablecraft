// Adds the 26.3 breeze entity skin (textures/entity/breeze/) to
// src/skins_extra.js, merging with the existing generated sheets.
// The official breeze skin is a 32x32 ghost layout (wide head band y0-7,
// body band y8-15 with a golden wind-core line, one arm, two tiny feet);
// models.js SKINS.breeze + DEFS.breeze map that layout onto a custom rig.
//   node tools/skins-breeze.mjs
import { PNG } from 'pngjs';
import fs from 'node:fs';
import path from 'node:path';

const ENT = '/home/user/proof/assets263/assets/minecraft/textures/entity/breeze/';
const OUT = path.join(process.cwd(), 'src/skins_extra.js');

function read(f) {
  const p = PNG.sync.read(fs.readFileSync(path.join(ENT, f)));
  if (p.width !== 32 || p.height !== 32) throw new Error('bad size ' + f + ` ${p.width}x${p.height}`);
  return { w: p.width, h: p.height, data: p.data };
}
// composite layers top-to-bottom (last non-transparent wins)
function compose(...pngs) {
  const [base] = pngs;
  const w = base.w, h = base.h;
  const out = new Uint8Array(w * h * 4);
  for (const p of [...pngs].reverse()) {
    for (let i = 0; i < w * h; i++) {
      const o = i * 4;
      if (p.data[o + 3] > 0) {
        out[o] = p.data[o]; out[o + 1] = p.data[o + 1]; out[o + 2] = p.data[o + 2]; out[o + 3] = p.data[o + 3];
      }
    }
  }
  return { w, h, data: out };
}
// same [w, h, ARGB palette, base64 indices] encoding as tools/skins.mjs
function toEntry(img) {
  const pal = new Map();
  const idx = [];
  for (let i = 0; i < img.w * img.h; i++) {
    const o = i * 4;
    const key = (img.data[o + 3] << 24) | (img.data[o] << 16) | (img.data[o + 1] << 8) | img.data[o + 2];
    let pi = pal.get(key);
    if (pi === undefined) { pi = pal.size; pal.set(key, pi); }
    idx.push(pi);
  }
  const palette = [...pal.entries()].map(([pi, argb]) => argb);
  let bin = '';
  for (const i of idx) bin += String.fromCharCode(i);
  return [img.w, img.h, palette, Buffer.from(bin, 'binary').toString('base64')];
}

const img = compose(read('breeze.png'), read('breeze_eyes.png'));
const entry = toEntry(img);

const src = fs.readFileSync(OUT, 'utf8');
const m = src.match(/export const EXTRA_SHEETS = (\{[\s\S]*\});/);
if (!m) throw new Error('EXTRA_SHEETS not found');
const sheets = JSON.parse(m[1]);
sheets.breeze = entry;
const js = `// GENERATED by tools/skins.mjs (1.21.5 base) + tools/skins-breeze.mjs (26.3 breeze) — do not edit.
// Vanilla entity skins in fablecraft sheet format [w, h, palette, base64].
export const EXTRA_SHEETS = ${JSON.stringify(sheets)};
`;
fs.writeFileSync(OUT, js);
console.log('added breeze sheet', entry[0] + 'x' + entry[1], 'palette', entry[2].length, '->', (js.length / 1024).toFixed(1), 'KB');
